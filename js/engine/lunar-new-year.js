/** Returns { month, day } of Lunar New Year for a Gregorian year, or null if out of range. */
export function lunarNewYear(year) {
  const v = DATES[year - FIRST_YEAR];
  if (v === undefined) return null;
  return { month: Math.floor(v / 100), day: v % 100 };
}

